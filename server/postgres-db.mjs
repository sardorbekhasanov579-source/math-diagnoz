// Neon PostgreSQL adapter for MATH-DIAGNOZ v1.6
// Same columns as SQLite v1.5, with BIGINT timestamps and durable file blobs.
import pg from 'pg'

const connectionString = String(process.env.DATABASE_URL||'').trim()
if (!connectionString || !/^postgres(?:ql)?:\/\/[^\s#]+$/.test(connectionString)) {
  throw new Error('DATABASE_URL noto‘g‘ri: faqat postgresql:// bilan boshlanadigan URL kiriting. .env matnini yoki DATABASE_URL= yozuvini joylamang.')
}
// Do not log secrets (the full DATABASE_URL contains the DB password).
let url
try { url = new URL(connectionString) } catch { throw new Error('DATABASE_URL formati noto‘g‘ri. Neon Connect dan faqat postgresql:// manzilini kiriting.') }
if (url.protocol !== 'postgres:' && url.protocol !== 'postgresql:') throw new Error('DATABASE_URL PostgreSQL manzili bo‘lishi kerak')
// Neon uses publicly trusted TLS certificates. Enforce certificate verification.
for (const key of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) url.searchParams.delete(key)
pg.types.setTypeParser(20, v => Number(v))
const pool = new pg.Pool({connectionString:url.toString(), ssl:{rejectUnauthorized:true}, max:5, connectionTimeoutMillis:15000, idleTimeoutMillis:30000, statement_timeout:30000})
pool.on('error', e => console.error('[POSTGRES]', e.message))

function translate(sql) {
  let query=sql
  if (/^\s*INSERT OR IGNORE INTO\s+/i.test(query)) {
    query=query.replace(/INSERT OR IGNORE INTO/i,'INSERT INTO')+' ON CONFLICT DO NOTHING'
  }
  query=query.replace(/\bAS\s+([a-z_]+[A-Z][A-Za-z0-9_]*)\b/g,(_,alias)=>`AS "${alias}"`)
  let num=0
  query=query.replace(/\?/g,()=>'$'+(++num))
  if(/^\s*INSERT INTO\s+(users|classes|schools)\b/i.test(query)&&!query.includes('RETURNING'))query+=' RETURNING id'
  return query
}
export async function get(sql,...args){const rows=(await pool.query(translate(sql),args)).rows;return rows[0]??null}
export async function all(sql,...args){return (await pool.query(translate(sql),args)).rows}
export async function run(sql,...args){const result=await pool.query(translate(sql),args);return {changes:result.rowCount,lastInsertRowid:result.rows[0]?.id??null}}

